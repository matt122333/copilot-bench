#!/usr/bin/env python3
"""Assemble a Harbor-runnable dataset directory for a chosen batch from batches/spec.yaml.

For each batch, this materializes:
    batches/<name>/dataset.toml       (dataset manifest listing selected tasks)
    batches/<name>/tasks/<task_id>/   (copied custom task, or stock task pulled from Harbor)

Usage:
  python3 tools/build_datasets.py [batch_id|all]
  python3 tools/build_datasets.py --list
"""
from __future__ import annotations
import argparse, os, shutil, subprocess, sys, textwrap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "batches", "spec.yaml")
CUSTOM_DIR = os.path.join(ROOT, "custom_tasks")
STOCK_CACHE = os.path.join(ROOT, ".harbor_datasets")  # gitignored

try:
    import yaml
except ImportError:
    print("pip install pyyaml  (or: uv tool install). Missing dependency.", file=sys.stderr)
    sys.exit(1)


def load_spec():
    if not os.path.exists(SPEC):
        sys.exit(f"spec not found: {SPEC}")
    return yaml.safe_load(open(SPEC))


def stock_source_path(sources, src):
    return sources.get(src, src)


def ensure_stock_download(ds_spec):
    """Download a stock dataset into a per-dataset cache dir and return that dir.

    `harbor dataset download <name>@<ver>` (run in a fresh dir) creates
    <shortname>/<task>/task.toml; we locate the dataset dir by walking for task.toml.
    """
    key = ds_spec.replace("/", "__").replace("@", "--")
    datacache = os.path.join(STOCK_CACHE, key)
    # already have it?
    if any(os.path.exists(os.path.join(r, "task.toml"))
           for r, _, _ in os.walk(datacache)):
        return datacache
    os.makedirs(datacache, exist_ok=True)
    print(f"  [harbor] downloading {ds_spec} ...")
    subprocess.run(["harbor", "dataset", "download", ds_spec],
                   cwd=datacache, check=True)
    return datacache


def find_task_dir(ds_root, task_id):
    # task dir may be ds_root/<task_id> or ds_root/<prefix>/<task_id>
    direct = os.path.join(ds_root, task_id)
    if os.path.isdir(direct):
        return direct
    for root, dirs, _ in os.walk(ds_root):
        for d in dirs:
            if d == task_id:
                return os.path.join(root, d)
    return None


def build_batch(b):
    name_dir = "B" + str(b["id"])
    out = os.path.join(ROOT, "batches", name_dir)
    tasks_dir = os.path.join(out, "tasks")
    if os.path.isdir(tasks_dir):
        shutil.rmtree(tasks_dir)
    os.makedirs(tasks_dir, exist_ok=True)

    task_names = []
    for t in b["tasks"]:
        src, tid = t["src"], t["id"]
        if src == "custom":
            sdir = os.path.join(CUSTOM_DIR, tid)
            if not os.path.isdir(sdir):
                print(f"  ! missing custom task {tid}", file=sys.stderr); continue
        else:
            ds_root = ensure_stock_download(stock_source_path(SOURCES, src))
            sdir = find_task_dir(ds_root, tid)
            if not sdir:
                print(f"  ! stock task {tid} not found under {ds_root}", file=sys.stderr); continue
        dst = os.path.join(tasks_dir, tid)
        shutil.copytree(sdir, dst, dirs_exist_ok=True)
        task_names.append(tid)
        print(f"  + {tid}  ({src})")

    rel = [f"tasks/{tid}" for tid in task_names]
    toml = (
        "# Generated by tools/build_datasets.py — do not edit.\n"
        f'[dataset]\nname = "copilotbench/{name_dir}"\nversion = "1.0.0"\n'
        f'description = "{b["name"]} | {b["coverage"]}"\nauthors = []\nkeywords = []\n'
        "tasks = [\n  " + ",\n  ".join(f'"{r}"' for r in rel) + "\n]\n"
    )
    with open(os.path.join(out, "dataset.toml"), "w") as f:
        f.write(toml)
    print(f"=> batches/{name_dir}: {len(task_names)} tasks ready "
          f"(harbor run -d batches/{name_dir})")
    return len(task_names)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("target", nargs="?", default="all",
                    help="batch id (1-5) or 'all'")
    ap.add_argument("-l", "--list", action="store_true", help="list batches and exit")
    args = ap.parse_args()

    global SOURCES
    spec = load_spec()
    SOURCES = spec["sources"]

    if args.list or args.target == "--list":
        for b in spec["batches"]:
            print(f"B{b['id']}: {b['name']} — {len(b['tasks'])} tasks")
        return

    batches = spec["batches"]
    if args.target != "all":
        batches = [b for b in batches if str(b["id"]) == args.target]
        if not batches:
            sys.exit(f"unknown batch: {args.target}")
    total = 0
    for b in batches:
        total += build_batch(b)
    print(f"done. {total} task-copies staged (stock pulled on clone via 'harbor dataset download').")


if __name__ == "__main__":
    main()